                    'periode_analisis'       => 'bulanan',
                    'form_layout_type'       => $cfg['tipe_form'],
                    'is_active'              => true,
                ]
            );

            // Perbarui layout type jika sudah ada
            $indicator->update([
                'form_layout_type' => $cfg['tipe_form'],
                'is_active'        => true,
            ]);

            // Jika form kustom (bukan daily_grid), buat atau update CustomFormFormat
            if ($cfg['tipe_form'] !== 'daily_grid' && !empty($cfg['columns'])) {
                $customFormat = CustomFormFormat::updateOrCreate(
                    [
                        'indicator_id' => $indicator->id,
                    ],
                    [
                        'unit_id'            => $unit->id,
                        'nama_format'        => $cfg['format_name'],
                        'table_title'        => $cfg['table_title'],
                        'row_type'           => $cfg['tipe_form'],
                        'schema'             => [
                            'columns'        => $cfg['columns'],
                            'rows'           => $cfg['rows'] ?? [],
                            'formula_config' => [
                                'numerator_col'   => collect($cfg['columns'])->firstWhere('role', 'numerator')['key'] ?? 'num',
                                'denominator_col' => collect($cfg['columns'])->firstWhere('role', 'denominator')['key'] ?? 'den',
                            ]
                        ],
                        'petunjuk_pengisian' => "Instrumen formulir pengumpul data mutu unit {$unit->nama}.",
                        'created_by'         => $adminId,
                        'is_active'          => true,
                    ]
                );

                // Sinkronkan ke schema indikator
                $indicator->update([
                    'form_schema' => [
                        'format_id'      => $customFormat->id,
                        'nama_format'    => $customFormat->nama_format,
                        'table_title'    => $customFormat->table_title,
                        'row_type'       => $customFormat->row_type,
                        'columns'        => $customFormat->schema['columns'] ?? [],
                        'rows'           => $customFormat->schema['rows'] ?? [],
                        'formula_config' => $customFormat->schema['formula_config'] ?? [],
                    ]
                ]);
            }

            $totalConfigured++;
        }

        $this->command->info("Berhasil mengonfigurasi {$totalConfigured} indikator dan format form pengumpul data multi-unit!");
    }
